import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import { createEmptyData } from '../src/prototype/dataLifecycle.js';
import { applyAttendanceCalendar } from '../src/prototype/attendanceCalendarService.js';
import { localDate, shiftDays } from '../src/prototype/domain.js';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const data=createEmptyData();
const today=localDate(), yesterday=shiftDays(today,-1);
const staff={id:'ui-owner',user_id:'ui-owner',display_name:'Super Admin',role_code:'super_admin',enabled:true};
data.members=[{id:'ui-member',full_name:'Calendar Test Member',member_code:'C001',category_id:'customer',created_at:new Date().toISOString(),previous_codes:[]}];
data.memberships=[{id:'ui-membership',member_id:'ui-member',start_date:shiftDays(today,-60),calculated_end_date:shiftDays(today,60),package_snapshot:{label:'Gym'},plan_snapshot:{label:'3 months'},record_origin:'live',created_at:shiftDays(today,-60)+'T00:00:00Z'}];
data.attendance=[{id:'ui-visit',member_id:'ui-member',attendance_date:today,checked_in_at:new Date().toISOString(),time_source:'current',member_category_snapshot:'Customer'}];
let saves=0;
const page=await browser.newPage({viewport:{width:1600,height:1000}});
const errors=[]; page.on('pageerror',error=>errors.push(error.message));
await mkdir('.local-db/ui-checks',{recursive:true});
await page.route('**/api/local/**',async route=>{
  const path=new URL(route.request().url()).pathname.split('/').at(-1);
  let body;
  if(path==='session') body={user:staff};
  else if(path==='workspace') body={data,staff};
  else if(path==='admin-accounts') body={accounts:[staff]};
  else if(path==='gym-commands') {
    const request=route.request().postDataJSON();
    assert.equal(request.command,'attendance.calendar');
    body={result:applyAttendanceCalendar(data,request.payload,{id:staff.id,role:staff.role_code},new Date().toISOString())};
    saves++;
  } else throw new Error(`Unexpected fixture route: ${path}`);
  await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(body)});
});
try {
  await page.goto(process.env.UI_URL || 'http://127.0.0.1:3000/');
  await page.getByRole('heading',{name:'Dashboard',exact:true}).waitFor();
  assert.equal(await page.getByText(/attendance records loaded/).count(),0);
  assert.equal(await page.locator('.sidebar-bottom').innerText(),'Admin');
  assert.equal(await page.locator('.dashboard-stats .stat-card').count(),4);
  const positions=await page.locator('.dashboard-overview > .panel').evaluateAll(nodes=>nodes.map(node=>({x:node.getBoundingClientRect().x,y:node.getBoundingClientRect().y})));
  assert.ok(positions[0].x<positions[1].x && positions[1].x<positions[2].x);
  assert.equal(positions[0].y,positions[2].y);
  await page.screenshot({path:'.local-db/ui-checks/dashboard-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'All active: 1',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Members',exact:true}).click();
  await page.getByRole('button',{name:'Open profile for Calendar Test Member'}).click();
  await page.getByRole('button',{name:'Edit attendance',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Attendance month').fill(yesterday.slice(0,7));
  await dialog.getByRole('button',{name:`${yesterday}: No recorded visit`,exact:true}).click();
  await dialog.getByLabel('Check-in time').fill('09:15');
  await dialog.getByLabel('Reason for changes').fill('Verified reception log');
  await page.screenshot({path:'.local-db/ui-checks/calendar-desktop.png',fullPage:true});
  await dialog.getByRole('button',{name:'Save changes'}).click();
  await dialog.waitFor({state:'hidden'}); assert.equal(saves,1);
  assert.ok(data.attendance.some(row=>row.attendance_date===yesterday));
  await page.getByRole('button',{name:'Edit attendance',exact:true}).click();
  await dialog.getByRole('button',{name:`${yesterday}: Present`,exact:true}).click();
  await dialog.getByLabel('Reason for changes').fill('Corrected duplicate paper entry');
  await dialog.getByRole('button',{name:'Save changes'}).click();
  await dialog.waitFor({state:'hidden'}); assert.equal(saves,2);
  assert.ok(data.attendance.find(row=>row.attendance_date===yesterday).voided_at);
  await page.getByRole('button',{name:'Edit attendance',exact:true}).click();
  await dialog.getByRole('button',{name:`${yesterday}: No recorded visit`,exact:true}).click();
  await dialog.getByLabel('Reason for changes').fill('Visit confirmed');
  await dialog.getByRole('button',{name:'Save changes'}).click();
  await dialog.waitFor({state:'hidden'}); assert.equal(saves,3);
  assert.equal(data.attendance.find(row=>row.attendance_date===yesterday).voided_at,null);
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'Dashboard',exact:true}).click();
  await page.screenshot({path:'.local-db/ui-checks/dashboard-mobile.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.getByRole('button',{name:'Members',exact:true}).click();
  await page.getByRole('button',{name:'Open profile for Calendar Test Member'}).click();
  await page.getByRole('button',{name:'Edit attendance',exact:true}).click();
  await dialog.getByRole('button',{name:`${yesterday}: Present`,exact:true}).click();
  await dialog.getByLabel('Reason for changes').fill('Mobile calendar check');
  await page.screenshot({path:'.local-db/ui-checks/calendar-mobile.png'});
  assert.ok(await dialog.evaluate(node=>node.getBoundingClientRect().right<=innerWidth));
  await dialog.getByRole('button',{name:'Save changes'}).click();
  await dialog.waitFor({state:'hidden'}); assert.equal(saves,4);
  await page.getByRole('button',{name:'Dashboard',exact:true}).click();
  await page.getByRole('button',{name:'Toggle theme'}).click();
  await page.screenshot({path:'.local-db/ui-checks/dashboard-mobile-dark.png',fullPage:true});
  staff.role_code='admin'; staff.display_name='Reception';
  await page.reload();
  await page.getByRole('heading',{name:'Dashboard',exact:true}).waitFor();
  assert.equal(await page.getByRole('button',{name:'Staff accounts',exact:true}).count(),0);
  await page.getByRole('button',{name:'Members',exact:true}).click();
  await page.getByRole('button',{name:'Open profile for Calendar Test Member'}).click();
  assert.equal(await page.getByRole('button',{name:'Edit attendance',exact:true}).count(),0);
  assert.deepEqual(errors,[]);
  console.log('Desktop/mobile layout, drilldown, calendar add/remove/restore and Staff restriction passed (synthetic API; no workspace data changed).');
} finally { await browser.close(); }
